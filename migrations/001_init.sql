CREATE TABLE IF NOT EXISTS services (
  id integer PRIMARY KEY,
  name text NOT NULL,
  kind text NOT NULL
);

CREATE TABLE IF NOT EXISTS masters (
  id integer PRIMARY KEY,
  name text NOT NULL,
  role text NOT NULL
);

CREATE TABLE IF NOT EXISTS master_services (
  master_id integer NOT NULL,
  service_id integer NOT NULL,
  PRIMARY KEY (master_id, service_id)
);

CREATE TABLE IF NOT EXISTS cars (
  id integer PRIMARY KEY,
  make text NOT NULL,
  model text NOT NULL,
  plate text NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS bookings (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  service_id integer NOT NULL,
  master_id integer NOT NULL,
  car_id integer NOT NULL,
  starts_at text NOT NULL,
  customer_name text NOT NULL,
  customer_phone text NOT NULL,
  status text NOT NULL
);

CREATE INDEX IF NOT EXISTS bookings_master_starts_at ON bookings (master_id, starts_at);

CREATE INDEX IF NOT EXISTS bookings_car_id ON bookings (car_id);

CREATE UNIQUE INDEX IF NOT EXISTS bookings_master_open_slot
  ON bookings (master_id, starts_at)
  WHERE status <> 'cancelled';
